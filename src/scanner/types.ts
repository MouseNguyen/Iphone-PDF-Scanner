export type Mode = 'document' | 'id' | 'photo';
export type Filter = 'auto' | 'color' | 'grayscale' | 'bw';
export type Point = { x: number; y: number };
export type Quad = [Point, Point, Point, Point];
export type SignaturePlacement = { assetId: string; imageUri: string; x: number; y: number; width: number; height: number; radians: number; mirrored: boolean };
export type Edit = { filter: Filter; quarterTurns: 0 | 1 | 2 | 3; corners?: Quad; signatures: SignaturePlacement[] };
export type OCRLine = { text: string; bounds: { x: number; y: number; width: number; height: number }; confidence: number };
export type OCR = { status: 'pending' | 'ready' | 'failed'; revision: number; lines: OCRLine[]; languages: string[]; errorCode?: string };
export type Page = { id: string; revision: number; baseUri: string; imageUri: string; edit: Edit; ocr: OCR };
export type Document = { schemaVersion: 1; id: string; revision: number; name: string; mode: Mode; createdAt: string; updatedAt: string; pageIds: string[]; pages: Page[]; saved: boolean; idSourcePages?: Page[] };
export type Capture = { status: 'cancelled' } | { status: 'captured'; imageUris: string[] };
export type Export = { uri: string; revision: number; imageOnlyPageIds: string[] };
export type Signature = { id: string; name: string; imageUri: string };
export type Stroke = { points: Point[]; color: string; width: number };
export type FailureCode = 'unsupported' | 'permission' | 'storage' | 'invalid_input' | 'stale_revision' | 'processing' | 'cancelled';
export type ScannerAPI = {
  librarySnapshot(): Promise<{ documents: Document[]; drafts: Document[]; unavailable: { id: string; reason: string }[] }>;
  listDocuments(): Promise<Document[]>;
  listDrafts(): Promise<Document[]>;
  loadDocument(id: string): Promise<Document>;
  createDraft(mode: Mode, imageUris: string[]): Promise<Document>;
  saveDocument(id: string, expectedRevision: number, name: string): Promise<Document>;
  discardDraft(id: string): Promise<void>;
  scanDocument(): Promise<Capture>;
  cancelProcessing(documentId: string): Promise<void>;
  recognitionLanguages(): Promise<string[]>;
  recognizePage(documentId: string, pageId: string, expectedRevision: number): Promise<Page>;
  exportPDF(documentId: string, expectedRevision: number, allowImageOnly: boolean): Promise<Export>;
  previewPDF(uri: string): Promise<void>;
  shareImages(uris: string[]): Promise<void>;
  libraryPreferences(): Promise<{ grid: boolean; sort: 'name' | 'date'; category: 'all' | Mode }>;
  setLibraryPreferences(value: { grid: boolean; sort: 'name' | 'date'; category: 'all' | Mode }): Promise<void>;
  composeIDDocument(documentId: string, expectedRevision: number): Promise<Document>;
  restoreIDSides(documentId: string, expectedRevision: number): Promise<Document>;
  editPage(documentId: string, pageId: string, expectedRevision: number, edit: Edit): Promise<Document>;
  reorderPages(documentId: string, expectedRevision: number, pageIds: string[]): Promise<Document>;
  removePage(documentId: string, expectedRevision: number, pageId: string): Promise<Document>;
  appendPages(documentId: string, expectedRevision: number, imageUris: string[], replacePageId?: string): Promise<Document>;
  composeID(frontUri: string, backUri: string): Promise<string>;
  saveSignature(strokes: Stroke[]): Promise<Signature>;
  listSignatures(): Promise<Signature[]>;
  renameSignature(id: string, name: string): Promise<void>;
  deleteSignature(id: string): Promise<void>;
  renameDocument(id: string, expectedRevision: number, name: string): Promise<Document>;
  deleteDocuments(ids: string[]): Promise<void>;
};
